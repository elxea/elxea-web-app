#!/usr/bin/env node
/**
 * marche-20260823-create-discount-codes.mjs
 *
 * One-off script: creates the 100 free-shipping discount codes for the
 * 8/23/2026 marché event (event_id = "marche-20260823" in elxea-cdp).
 *
 * BLOCKED as of 2026-08-16: the elxea-ec-api custom app token in
 * .env.local does NOT have the `write_discounts` access scope (confirmed
 * empirically — discountCodeFreeShippingCreate returns ACCESS_DENIED).
 * Adding a scope to an existing Shopify custom app can only be done via
 * the Admin UI (Settings > Apps and sales channels > Develop apps >
 * elxea-ec-api > Configuration > check `write_discounts` (and ideally
 * `read_discounts` for future idempotent re-runs) > Save > API credentials
 * tab > "Update access scopes"). There is no API path to self-grant scopes
 * — this is a deliberate Shopify platform restriction. No token rotation
 * is normally required for a scope-only change.
 *
 * Once the scope is granted, run:
 *   node scripts/marche-20260823-create-discount-codes.mjs
 *
 * Design:
 *   - Free shipping discount codes (discountCodeFreeShippingCreate), not
 *     percentage/fixed-amount — Boss decision 2026-08-16 (see
 *     circl-boss/deliverables/event-coupon-setup.md): the code exists to
 *     be a *tracking key* for event->online-purchase attribution, not to
 *     discount price. Maximizing redemption rate matters more than
 *     minimizing per-code cost, and free shipping removes the #1 first-
 *     purchase friction (checkout shipping-cost sticker shock) without a
 *     visible price cut.
 *   - usageLimit: 1, appliesOncePerCustomer: true — single-use per code,
 *     matching the 1:1 slip-number <-> code design in slip-code-mapping.csv
 *     (generated by generate-codes.mjs, committed alongside this script's
 *     output as marche-20260823-codes.json for the record).
 *   - endsAt = startsAt + 90 days. Rationale: the event is a one-time
 *     in-person touch; the conversion window (event -> "I remembered and
 *     bought online") is unpredictable and typically longer than a
 *     standard promo window because there is no repeat exposure pushing
 *     the recipient to act (unlike an email drip). 90 days covers a full
 *     season of gift-buying occasions without being open-ended (which
 *     would blur "was this really the marché lead" attribution if used
 *     e.g. 8 months later). Shorter (7-30d) risks under-counting true
 *     conversions per the explicit purpose stated in Task instructions
 *     ("短すぎると取りこぼす").
 *   - combinesWith: all false — conservative default, does not stack with
 *     other active promotions (prevents free-shipping + other discount
 *     stacking abuse; can be revisited if a legitimate need arises).
 *   - No customer/segment restriction — anyone can redeem (leads are
 *     collected at the booth from the general public).
 *
 * Idempotency: Shopify enforces global code uniqueness at creation time.
 * Re-running this script after a partial failure is safe — codes that
 * already exist come back as a userError ("has already been taken") which
 * this script treats as "already created, skip", not a fatal error.
 *
 * SAFETY: this script only CREATES new discount codes. It never modifies
 * or deletes any pre-existing discount (constraint: 既存の...割引コードを
 * 改変・削除しない). It reads no other Shopify resource.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const CODES_JSON = join(__dirname, "marche-20260823-codes.json");
const RESULTS_JSON = join(__dirname, "marche-20260823-create-results.json");

const DEFAULT_ENV_PATH = "/Users/setaka/github/elxea/products/elxea-web-app/.env.local";
function loadShopifyCreds(envPath = process.env.ELXEA_SHOPIFY_ENV_PATH || DEFAULT_ENV_PATH) {
  let domain = process.env.SHOPIFY_STORE_DOMAIN || "";
  let token = process.env.SHOPIFY_ADMIN_ACCESS_TOKEN || "";
  if (!domain || !token) {
    const text = readFileSync(envPath, "utf-8");
    for (const line of text.split("\n")) {
      const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
      if (!m) continue;
      const v = m[2].trim().replace(/^["']|["']$/g, "");
      if (m[1] === "SHOPIFY_STORE_DOMAIN" && !domain) domain = v;
      if (m[1] === "SHOPIFY_ADMIN_ACCESS_TOKEN" && !token) token = v;
    }
  }
  if (!domain || !token) throw new Error("Shopify credentials incomplete");
  return { domain, token };
}

function makeClient({ domain, token }) {
  const endpoint = `https://${domain}/admin/api/2025-04/graphql.json`;
  return async function gql(query, variables = {}) {
    for (let attempt = 0; attempt < 5; attempt++) {
      const res = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json", "X-Shopify-Access-Token": token },
        body: JSON.stringify({ query, variables }),
      });
      if (res.status === 429 || res.status >= 500) {
        await new Promise((r) => setTimeout(r, 1000 * 2 ** attempt));
        continue;
      }
      const json = await res.json();
      if (json.errors) {
        const throttled = json.errors.some((e) => e.extensions?.code === "THROTTLED");
        if (throttled) {
          await new Promise((r) => setTimeout(r, 1000 * 2 ** attempt));
          continue;
        }
        return { errors: json.errors };
      }
      return json.data;
    }
    throw new Error("Shopify Admin API: retries exhausted");
  };
}

const MUTATION = `
mutation discountCodeFreeShippingCreate($freeShippingCodeDiscount: DiscountCodeFreeShippingInput!) {
  discountCodeFreeShippingCreate(freeShippingCodeDiscount: $freeShippingCodeDiscount) {
    codeDiscountNode { id }
    userErrors { field message }
  }
}`;

async function main() {
  if (!existsSync(CODES_JSON)) {
    throw new Error(`${CODES_JSON} not found — run generate-codes.mjs first (see marche-coupons scratch dir / deliverable doc for the source list, or regenerate with the same alphabet/format documented in event-coupon-setup.md)`);
  }
  const rows = JSON.parse(readFileSync(CODES_JSON, "utf-8"));
  const { domain, token } = loadShopifyCreds();
  const gql = makeClient({ domain, token });

  const now = new Date();
  const endsAt = new Date(now.getTime() + 90 * 86400_000);

  const results = [];
  let created = 0, skipped = 0, failed = 0;

  for (const { slip_no, code } of rows) {
    const vars = {
      freeShippingCodeDiscount: {
        title: `marche-20260823:${slip_no}`,
        code,
        startsAt: now.toISOString(),
        endsAt: endsAt.toISOString(),
        usageLimit: 1,
        appliesOncePerCustomer: true,
        destination: { all: true },
        combinesWith: { orderDiscounts: false, productDiscounts: false, shippingDiscounts: false },
      },
    };
    const data = await gql(MUTATION, vars);
    if (data.errors) {
      const denied = data.errors.some((e) => e.extensions?.code === "ACCESS_DENIED");
      results.push({ slip_no, code, status: "failed", error: data.errors.map(e => e.message).join("; ") });
      failed++;
      if (denied) {
        console.error(`[ABORT] ${slip_no} ${code}: access denied (write_discounts scope missing). Stopping — see script header for the unblock path.`);
        break;
      }
      console.error(`[FAIL] ${slip_no} ${code}: ${data.errors.map(e => e.message).join("; ")}`);
      continue;
    }
    const ue = data.discountCodeFreeShippingCreate.userErrors;
    if (ue && ue.length) {
      const alreadyTaken = ue.some((e) => /taken|already/i.test(e.message));
      if (alreadyTaken) {
        results.push({ slip_no, code, status: "already_exists" });
        skipped++;
        continue;
      }
      results.push({ slip_no, code, status: "failed", error: ue.map(e => e.message).join("; ") });
      failed++;
      console.error(`[FAIL] ${slip_no} ${code}: ${ue.map(e => e.message).join("; ")}`);
      continue;
    }
    const id = data.discountCodeFreeShippingCreate.codeDiscountNode.id;
    results.push({ slip_no, code, status: "created", shopify_id: id });
    created++;
  }

  writeFileSync(RESULTS_JSON, JSON.stringify(results, null, 2));
  console.log(`created=${created} already_exists=${skipped} failed=${failed} total=${rows.length}`);
  console.log(`results written to ${RESULTS_JSON}`);
  if (failed > 0) process.exitCode = 1;
}

main().catch((e) => {
  console.error(`FAILED: ${e.message}`);
  process.exit(1);
});
