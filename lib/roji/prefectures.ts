/** 47 都道府県のいずれか。地図描画のキーになる。 */
export type Prefecture = (typeof PREFECTURES)[number];

/** 都道府県名の集合 (存在判定用。配列の線形探索を避ける)。 */
const PREFECTURE_SET: ReadonlySet<string> = new Set(PREFECTURES);

/** 任意の文字列が 47 都道府県の正式名称かを判定する型ガード。 */
export function isPrefecture(value: string): value is Prefecture {
  return PREFECTURE_SET.has(value);
}

/**
 * 全国地方公共団体コード順 (北から南) の並び順インデックス。
 * 未知の値には -1 を返す (呼び出し側で末尾に寄せる等の判断ができるように)。
 */
export function prefectureOrder(value: string): number {
  return PREFECTURES.indexOf(value as Prefecture);
}
